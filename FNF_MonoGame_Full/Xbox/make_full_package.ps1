###############################################################################
# FNF MonoGame - build a self-contained ("full") Xbox package
#
# Takes the signed code-only package produced by build_xbox.ps1 -Release
# (AppPackages\FNF_Xbox_<ver>_x64_Test\FNF_Xbox_<ver>_x64.msix), adds the whole
# ..\Content folder to it and re-signs it with the same certificate.
# Installing the result needs NO separate content upload: the game uses the
# package's Content folder (a Content folder uploaded to LocalState still wins).
#
# USAGE:
#   .\make_full_package.ps1                       # newest package in AppPackages
#   .\make_full_package.ps1 -Msix <path.msix> -Thumbprint <cert thumbprint>
# Output: <package folder>\FNF_Xbox_<ver>_x64_full.msix (+ .cer + Dependencies next to it)
###############################################################################
param(
    [string]$Msix = "",
    [string]$Content = (Join-Path $PSScriptRoot "..\Content"),
    [string]$Thumbprint = "0CF8C36AC5F8A1D97017E9FB18CE21AFDD8176A3",
    [string]$Pfx = (Join-Path $PSScriptRoot "mohammad_aljafari.pfx"),
    [string]$PfxPassword = ""
)
$ErrorActionPreference = "Stop"

$kits = (Get-ItemProperty "HKLM:\SOFTWARE\Microsoft\Windows Kits\Installed Roots" -Name KitsRoot10 -ErrorAction SilentlyContinue).KitsRoot10
if (-not $kits) { $kits = "C:\Program Files (x86)\Windows Kits\10\" }
$makeappx = Get-ChildItem "$kits\bin\*\x64\makeappx.exe" | Sort-Object FullName | Select-Object -Last 1
$signtool = Get-ChildItem "$kits\bin\*\x64\signtool.exe" | Sort-Object FullName | Select-Object -Last 1
if (-not $makeappx -or -not $signtool) { throw "makeappx/signtool not found (install the Windows 10 SDK)" }

if (-not $Msix) {
    $Msix = (Get-ChildItem (Join-Path $PSScriptRoot "AppPackages") -Recurse -Filter "FNF_Xbox_*_x64.msix" |
        Where-Object { $_.Name -notlike "*_full.msix" } | Sort-Object LastWriteTime | Select-Object -Last 1).FullName
}
if (-not $Msix -or -not (Test-Path $Msix)) { throw "code package not found - run .\build_xbox.ps1 -Release first" }
$Content = (Resolve-Path $Content).Path
$outMsix = $Msix -replace '\.msix$', '_full.msix'
$work = Join-Path ([IO.Path]::GetTempPath()) ("fnf_full_" + [Guid]::NewGuid().ToString("N"))

Write-Host "Code package : $Msix"
Write-Host "Content      : $Content"
Write-Host "Output       : $outMsix"

# 1. unpack the code package
& $makeappx.FullName unpack /p $Msix /d $work /o | Out-Null
if ($LASTEXITCODE -ne 0) { throw "makeappx unpack failed" }
# signature/blockmap/content types are regenerated by pack + sign
Remove-Item -Force -ErrorAction SilentlyContinue (Join-Path $work "AppxSignature.p7x"), (Join-Path $work "AppxBlockMap.xml"), (Join-Path $work "[Content_Types].xml")

# 2. add the game content (skip dev leftovers)
$dest = Join-Path $work "Content"
robocopy $Content $dest /E /MT:16 /R:1 /W:1 /NFL /NDL /NP /NJH /NJS /XF config_backup.tar.gz *.bak *.log Thumbs.db desktop.ini | Out-Null
if ($LASTEXITCODE -ge 8) { throw "robocopy failed ($LASTEXITCODE)" }
$n = (Get-ChildItem $dest -Recurse -File).Count
Write-Host "Content files: $n"

# 3. pack + sign
$packLog = & $makeappx.FullName pack /d $work /p $outMsix /o
if ($LASTEXITCODE -ne 0) { $packLog | Select-Object -Last 20; throw "makeappx pack failed" }
# the manifest Publisher must equal the certificate subject (CN=mohammad aljafari)
if (Test-Path "Cert:\CurrentUser\My\$Thumbprint") {
    & $signtool.FullName sign /fd SHA256 /sha1 $Thumbprint /s My $outMsix
} elseif ($PfxPassword) {
    & $signtool.FullName sign /fd SHA256 /f $Pfx /p $PfxPassword $outMsix
} else {
    & $signtool.FullName sign /fd SHA256 /f $Pfx $outMsix
}
if ($LASTEXITCODE -ne 0) { throw "signtool sign failed" }
Remove-Item -Recurse -Force $work

$sig = Get-AuthenticodeSignature $outMsix
Write-Host ("Signed: {0} by {1}" -f $sig.Status, $sig.SignerCertificate.Subject) -ForegroundColor Green
Write-Host ("Size  : {0:N0} MB" -f ((Get-Item $outMsix).Length / 1MB)) -ForegroundColor Green

/// <summary>

/// Psych Engine character JSON format (characters/*.json in mod folders).

/// </summary>

public class PsychCharacterJson

{

    [JsonProperty("animations")] public List<PsychCharacterAnim> Animations { get; set; }

    [JsonProperty("image")] public string Image { get; set; }

    [JsonProperty("scale")] public float Scale { get; set; } = 1f;

    [JsonProperty("sing_duration")] public float SingDuration { get; set; } = 4f;

    [JsonProperty("healthicon")] public string HealthIcon { get; set; }

    [JsonProperty("position")] public float[] Position { get; set; }

    [JsonProperty("camera_position")] public float[] CameraPosition { get; set; }

    [JsonProperty("flip_x")] public bool FlipX { get; set; }

    [JsonProperty("no_antialiasing")] public bool NoAntialiasing { get; set; }

    [JsonProperty("healthbar_colors")] public int[] HealthBarColors { get; set; }



    /// <summary>

    /// Convert Psych Engine character data to the engine's CharacterJsonData format.

    /// </summary>

    public CharacterJsonData ToCharacterJsonData(string charName = null)

    {

        var result = new CharacterJsonData

        {

            AssetPath = string.IsNullOrEmpty(Image) ? $"characters/{charName ?? "dad"}" : Image,

            FlipX = FlipX,

            IsPixel = NoAntialiasing,

            Scale = Scale,

            SingTime = SingDuration,

            Offsets = null, // Psych position is applied separately as top-left offset, not feet global offset

            CameraOffsets = CameraPosition,

            Position = Position,

            StartingAnimation = "idle",

            RenderType = "sparrow",

            Animations = new List<CharacterAnimJsonData>()

        };



        if (Animations != null)

        {

            foreach (var anim in Animations)

            {

                result.Animations.Add(new CharacterAnimJsonData

                {

                    Name = anim.Anim ?? "idle",

                    Prefix = anim.Name ?? "",

                    Offsets = anim.Offsets,

                    Looped = anim.Loop,

                    FrameRate = anim.Fps > 0 ? anim.Fps : 24,

                    FrameIndices = (anim.Indices != null && anim.Indices.Length > 0) ? anim.Indices : null

                });

            }

        }



        result.PsychHealthIcon = HealthIcon;
        if (HealthBarColors != null && HealthBarColors.Length >= 3)

        {

            result.HealthBarColor = $"#{HealthBarColors[0]:X2}{HealthBarColors[1]:X2}{HealthBarColors[2]:X2}";

        }



        return result;

    }

}




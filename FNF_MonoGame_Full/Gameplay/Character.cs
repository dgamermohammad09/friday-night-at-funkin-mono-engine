        if (!_isDarkVariant || _normalChar != null || string.IsNullOrEmpty(_normalBaseName)) return;















        _normalChar = new Character(_normalBaseName, Position.X, Position.Y);















        _normalChar.LoadJsonData(assets, _normalBaseName);















        _normalChar.LoadSprites(game);















        _normalChar.SetFlipForRole(FlipX);















        _normalChar.Alpha = 0.0001f;















    }















    















    public virtual void Update(float deltaTime)















    {















        _sprite?.Update(deltaTime);
        UpdateCountAnimation(); if (AnimLocked && (_sprite == null || _sprite.Finished)) AnimLocked = false; // Bopper.onAnimationFinished
        // BaseCharacter.onUpdate: when an anim finishes and \'<anim>-hold\' exists, play it.
        if (_sprite != null && _sprite.Finished && _currentAnimation != null
            && !_currentAnimation.EndsWith("-hold") && _jsonAnimMappings != null && _jsonAnimMappings.ContainsKey(_currentAnimation + "-hold"))
        { float keepHold = _animHoldTime; PlayAnimation(_currentAnimation + "-hold"); _animHoldTime = keepHold; } // holdTimer is not reset by playAnimation
        // Psych Character.update 249-262: Hey!/cheer events set heyTimer; when it runs out the hey/cheer anim is
        // cut and the character dances right away (port kept playing the whole hey anim).
        if (PsychHeyTimer > 0f) { PsychHeyTimer -= deltaTime; if (PsychHeyTimer <= 0f) { PsychHeyTimer = 0f; var __ha = CurrentAnimation ?? ""; if (__ha == "hey" || __ha == "cheer") PsychDanceNow(); } }







        _normalChar?.Update(deltaTime);















        if (_normalChar != null)















        {















            _normalChar.Position = new Vector2(Position.X + _normalCharOffset.X, Position.Y + _normalCharOffset.Y);















            _normalChar.Scale = Scale;















            _normalChar.FlipX = FlipX;















        }















        















        // Loop-transition anims (original pico-holding-nene.hxc onAnimationComplete):















        // laughEnd -> laughEnd-loop, deathConfirm -> deathConfirm-loop.















        // These take priority over the return-to-idle logic below.















        if (_sprite != null && _sprite.Finished && _jsonAnimMappings != null)















        {















            if (_currentAnimation == "laughEnd" && _jsonAnimMappings.ContainsKey("laughEnd-loop"))















            {















                PlayAnimation("laughEnd-loop");















                return;















            }















            if (_currentAnimation == "deathConfirm" && _jsonAnimMappings.ContainsKey("deathConfirm-loop"))















            {















                PlayAnimation("deathConfirm-loop");















                return;















            }















        }































        // Don't auto-return to idle during death animations















        if (IsDead) return;















        















        // Return to idle after sing/miss animation hold time















        // Original FNF: holdTimer counts down, returns to idle when holdTimer <= 0 AND anim finished















        // With loop=false, _sprite.Finished becomes true when anim plays through once















        if (_isSingOrMiss)















        {















            // BaseCharacter.onUpdate (characterType BF): justPressedNote() resets holdTimer; the pose is kept while any note key is held
            bool __bfSing = IsPlayerType && _currentAnimation != null && _currentAnimation.StartsWith("sing") && !_currentAnimation.EndsWith("-end");
            if (__bfSing && PlayerJustPressedNote) _animHoldTime = SingHoldSeconds(_currentAnimation, JsonData?.SingTime ?? 4f);
            _animHoldTime -= deltaTime;















            if (_animHoldTime <= 0 && !(__bfSing && PlayerHoldingNote)) // shouldStopSinging = !isHoldingNote()















            {















                bool finished = _sprite != null && (_sprite.Finished || (_currentAnimation != null && _currentAnimation.EndsWith("-hold"))); // looped '-hold' never finishes: holdTimer alone ends it (BaseCharacter.onUpdate)















                // One-shot speech/cutscene anims (ugh, redheads, shoot, etc.) must play fully —















                // never force-cut them. Sing/miss anims use a 0.5s safety timeout.















                bool timedOut = !_isOneShotSpeechAnim && _animHoldTime < -0.5f; if (VSliceSingTimer && _currentAnimation != null && _currentAnimation.StartsWith("sing")) finished = true; // BaseCharacter.onUpdate: dance(true) once holdTimer > singTimeSec















                if ((finished || timedOut) && !(NoBeatDance && _isOneShotSpeechAnim)) // one-shot anims return to idle via the beat dance only; danceEvery = 0 -> hold the last frame (stress-pico ending)















                {















                    PlayAnimation("idle");















                }















            }















        }















    }















    















    /// <summary>Character-script dance() override. Return true when the subclass handled the beat.</summary>
    protected virtual bool DanceOverride() => false;
    /// <summary>V-Slice character scripts that replace onNoteHit/onNoteMiss and set danceEvery = 0
    /// (pico-blazin.hxc / darnell-blazin.hxc): no sing/miss anims, no beat dance; the script plays every anim.</summary>
    public bool ScriptAnimOnly;
    /// <summary>danceEvery = 0 (2hot.hxc ending): Bopper.onBeatHit never dances; BaseCharacter hold timer still plays idle.</summary>
    public bool NoBeatDance;
    /// <summary>Bopper.hasDanced = value (next dual dance: false -> danceLeft, true -> danceRight).</summary>
    public void SetHasDanced(bool value) => _danceLeft = value;
    /// <summary>Psych heyTimer (seconds) set by the Hey! event.</summary>
    public float PsychHeyTimer;
    /// <summary>Psych Character.dance(): danceIdle toggles danceLeft/danceRight, else idle (forced).</summary>
    public void PsychDanceNow()
    {
        if (_hasDualDance) { _danceLeft = !_danceLeft; PlayAnimation(_danceLeft ? "danceLeft" : "danceRight", true); }
        else PlayAnimation("idle", true);
    }
    /// <summary>Bopper.canPlayOtherAnims == false: set by playAnimation(name, restart, ignoreOther=true); cleared in
    /// onAnimationFinished. While set, dance()/idle requests are ignored (only "sing*" + exclusions may play).</summary>
    public bool AnimLocked;
    public void PlayAnimationLocked(string anim) { PlayAnimation(anim, force: true); AnimLocked = true; }
    /// <summary>playAnimation(name, restart, ignoreOther, reversed=true) (pico-blazin hitSpin).</summary>
    public void PlayAnimationReversed(string anim) { PlayAnimation(anim, force: true); _sprite?.StartReversed(); }

    public virtual void Dance(int beat)















    {
        if (ScriptAnimOnly) return; // danceEvery = 0
        if (_isSingOrMiss && IsPlayerType && PlayerHoldingNote && _currentAnimation != null && _currentAnimation.StartsWith("sing") && !_currentAnimation.EndsWith("-end")) return; // BaseCharacter.dance(): isSinging() blocks the beat dance (BF holding a note)
        if (NoBeatDance) return; // danceEvery = 0 set by a song script: no beat dances, sing hold still returns to idle
        if (AnimLocked && _sprite != null && !_sprite.Finished) return; // Bopper: !canPlayOtherAnims















        // Don't dance during death















        if (IsDead) return;















        















        // Characters dance on even beats (or based on their dance interval)















        if (beat % _danceInterval == 0 && beat != _lastDanceBeat)















        {















            _lastDanceBeat = beat;















            // Don't interrupt one-shot speech/cutscene anims (original: holdTimer = 0 but anim must finish)















            if (_isSingOrMiss && _sprite != null && !_sprite.Finished)















                return;















            // BaseCharacter.dance(false): a non-idle special animation (not dance*/idle*) that is still playing blocks the dance;
            // a looped one (pico-speaker shootN-hold) blocks it until the script plays something else.
            { string __ca = CurrentAnimation ?? ""; if (!_isSingOrMiss && __ca.Length > 0 && !__ca.StartsWith("dance") && !__ca.StartsWith("idle") && _sprite != null && !_sprite.Finished) return; }
            if (DanceOverride()) return; // character script dance() (e.g. nene.hxc knife states)

            if (!_isSingOrMiss || _animHoldTime <= 0)















            {















                if (_hasDualDance)















                {















                    // GF-type: alternate between danceLeft and danceRight each beat















                    _danceLeft = !_danceLeft;















                    PlayAnimation(_danceLeft ? "danceLeft" : "danceRight", true);















                }















                else















                {















                    // FlxAnimationController.play("idle", Force=false): restart only if a different animation is
                    // playing or the idle has finished (original Bopper.dance / Psych Character.dance).
                    if (CurrentAnimation != "idle" || _sprite == null || _sprite.Finished)
                        PlayAnimation("idle", true);















                }















            }















        }















    }















    















    /// <summary>V-Slice NoteKind.suffix of a scripted note kind (PlayScene.VSliceScripts), null = engine default.</summary>
    public static Func<string, string> NoteKindSuffixResolver;
    public void Sing(int direction, string noteKind = null)















    {
        if (ScriptAnimOnly) return;















        string baseAnim = direction switch















        {















            0 => "singLEFT",















            1 => "singDOWN",















            2 => "singUP",















            3 => "singRIGHT",















            _ => "idle"















        };































        // Special note-kind animations that bypass sing (e.g., tankman "ugh", "hehPrettyGood").















        // Original FNF: tankman.hxc intercepts these note kinds and plays the standalone animation.















        if (!string.IsNullOrEmpty(noteKind) && _jsonAnimMappings != null &&















            _jsonAnimMappings.ContainsKey(noteKind))















        {















            _lastSingAnim = noteKind;















            PlayAnimation(noteKind, force: true);















            return;















        }































        // Use note kind from chart data for animation suffix (e.g., "mom" → singLEFT-alt)















        string anim = baseAnim;















        if (!string.IsNullOrEmpty(noteKind) && _hasAltAnims)















        {















            // In original FNF, note kind "mom" maps to -alt suffix for parents character















            string suffix = NoteKindSuffixResolver?.Invoke(noteKind) ?? (noteKind.Equals("mom", StringComparison.OrdinalIgnoreCase) ? "alt" : noteKind);















            string altAnim = baseAnim + "-" + suffix;















            if (_jsonAnimMappings != null && _jsonAnimMappings.ContainsKey(altAnim))















                anim = altAnim;















        }















        _lastSingAnim = anim;















        PlayAnimation(anim, force: true);















    }















    















    /// <summary>















    /// Continue holding the current sing animation (sustain notes).















    /// Plays the -hold variant if available, without toggling alt.















    /// </summary>















    public void HoldSing(int direction)















    {
        if (ScriptAnimOnly) return;















        // If already holding, keep the hold time refreshed















        if (_isSingOrMiss)















        {















            float singTime = JsonData?.SingTime ?? 4f;















            float holdTime = SingHoldSeconds(_currentAnimation, singTime);















            















            _animHoldTime = holdTime;















        }















        















        // Try to play the -hold animation variant















        if (!string.IsNullOrEmpty(_lastSingAnim))















        {















            string holdAnim = _lastSingAnim + "-hold";















            if (_jsonAnimMappings != null && _jsonAnimMappings.ContainsKey(holdAnim))















            {















                // BaseCharacter.onUpdate: '<anim>-hold' only starts once the base animation has finished
                if (_currentAnimation != holdAnim && (_sprite == null || _sprite.Finished))















                    PlayAnimation(holdAnim);















                return;















            }















        }















        















        // Fallback: just refresh the sing pose without restarting animation















        if (_isSingOrMiss)















        {















            float singTime = JsonData?.SingTime ?? 4f;















            _animHoldTime = SingHoldSeconds(_currentAnimation, singTime);















        }















    }















    















    /// <summary>PlayState.processNotes: if (isSinging()) holdTimer = 0 (hold note still being played by the bot / opponent).</summary>
    public void KeepSinging()
    {
        if (!_isSingOrMiss || _currentAnimation == null || !_currentAnimation.StartsWith("sing") || _currentAnimation.EndsWith("-end")) return;
        _animHoldTime = SingHoldSeconds(_currentAnimation, JsonData?.SingTime ?? 4f);
    }

    /// <summary>BaseCharacter.playSingAnimation(dir, miss, suffix): plays exactly 'sing{DIR}{miss}-{suffix}' (restart),
    /// used by character scripts that pass their own suffix (sserafim-sakura.hxc joint/bf1/bf2).</summary>
    public void SingSuffix(int direction, string suffix, bool miss = false)
    {
        if (ScriptAnimOnly) return;
        string dir = (direction & 3) switch { 0 => "LEFT", 1 => "DOWN", 2 => "UP", _ => "RIGHT" };
        string anim = "sing" + dir + (miss ? "miss" : "") + (string.IsNullOrEmpty(suffix) ? "" : "-" + suffix);
        _lastSingAnim = anim;
        PlayAnimation(anim, force: true);
    }


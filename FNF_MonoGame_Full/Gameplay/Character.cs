    /// <summary>















    /// Approximate midpoint of the character sprite (center of current frame).















    /// Matches HaxeFlixel's getMidpoint(): position + (frameWidth*scale/2, frameHeight*scale/2).















    /// Used for camera follow calculations.















    /// </summary>















    public virtual Vector2 GetMidpoint()















    {















        // Original HaxeFlixel: getMidpoint() = (x + width*0.5, y + height*0.5)















        // Position already includes globalOffsets (CharOffsets), so do NOT add them again.















        // Original BaseCharacter.resetCameraFocusPoint(): width/height are those of the IDLE frame
        // captured at placement (updateHitbox after dance(true)); they do NOT follow the current
        // animation. Using the live frame made the camera target drift while characters sang.
        // Psych Character (scale 1 / updateHitbox before any playAnim): width/height = frames[0] of the atlas.
        var ff = StageUsesPsychPositioning ? _sprite?.Sheet?.FirstFrame : null;
        if (ff != null)
        {
            float fw = ff.FrameWidth > 0 ? ff.FrameWidth : ff.SourceRect.Width, fh = ff.FrameHeight > 0 ? ff.FrameHeight : ff.SourceRect.Height;
            return new Vector2(Position.X + fw * Math.Abs(Scale) / 2f, Position.Y + fh * Math.Abs(Scale) / 2f);
        }
        var pfs = _sprite?.PositioningFrameSize ?? (0, 0);
        float halfW = (pfs.Width > 0 ? pfs.Width : GetFrameWidth()) * Scale / 2f;
        float halfH = (pfs.Height > 0 ? pfs.Height : GetFrameHeight()) * Scale / 2f;
        return new Vector2(Position.X + halfW, Position.Y + halfH);















    }















    
















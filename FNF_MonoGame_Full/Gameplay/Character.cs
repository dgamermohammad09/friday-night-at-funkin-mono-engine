    /// <summary>















    /// Load character data from JSON (data/characters/{name}.json).















    /// Must be called before LoadSprites for JSON animation mappings to work.















    /// </summary>















    public void LoadJsonData(AssetManager assets, string originalName = null)















    {















        OriginalName = originalName ?? Name;















        string charName = OriginalName;















        // Try Psych Engine format first so mods can override base-game characters
        var psychData = assets.LoadJson<PsychCharacterJson>($"characters/{charName}");
        // On a Psych Engine stage, characters the mod does not ship (bf, gf, bf-dead) come from
        // Psych's own assets/shared/characters (copied to Content/data/psych), not V-Slice data.
        if (psychData == null && PsychStageActive)
            psychData = assets.LoadJson<PsychCharacterJson>($"data/psych/characters/{charName}");
        if (psychData != null)
        {
            JsonData = psychData.ToCharacterJsonData(charName);
            PsychCharacterOffset = psychData.Position;
            Console.WriteLine($"[MODS] Loaded Psych Engine character: {charName} (image={psychData.Image ?? "none"}) pos=({psychData.Position?[0] ?? 0},{psychData.Position?[1] ?? 0})");
        }



        // Fallback to base-game format

        if (JsonData == null)

        {

            JsonData = assets.LoadJson<CharacterJsonData>($"data/characters/{charName}");

        }













        if (JsonData == null && charName != Name)

        {

            // Try Psych Engine format first so mods can override base-game characters
            var psychDataFallback = assets.LoadJson<PsychCharacterJson>($"characters/{Name}");
            if (psychDataFallback != null)
            {
                JsonData = psychDataFallback.ToCharacterJsonData(Name);
                PsychCharacterOffset = psychDataFallback.Position;
                Console.WriteLine($"[MODS] Loaded Psych Engine character (fallback): {Name} (image={psychDataFallback.Image ?? "none"}) pos=({psychDataFallback.Position?[0] ?? 0},{psychDataFallback.Position?[1] ?? 0})");
            }



            // Fallback to base-game format

            if (JsonData == null)

            {

                JsonData = assets.LoadJson<CharacterJsonData>($"data/characters/{Name}");

            }

        }















        















        if (JsonData != null)















        {















            CameraOffsets = JsonData.CameraOffsets;















            CharOffsets = JsonData.Offsets;















            

















            // PsychCharacterOffset is set only when a Psych Engine JSON is loaded; base-game

            // characters must keep it null so they use feet-based positioning on base stages.

            // Detect dark variant and prepare normalChar fallback















            // Original sources: bf-dark.hxc, gf-dark.hxc, nene-dark.hxc, pico-dark.hxc, spooky-dark.hxc















            if (charName.EndsWith("-dark", StringComparison.OrdinalIgnoreCase))















            {















                _isDarkVariant = true;















                // Each dark variant has specific normalChar mapping per original source















                if (charName.Equals("bf-dark", StringComparison.OrdinalIgnoreCase))















                {















                    _normalBaseName = "bf";















                    _normalCharOffset = new Vector2(-1f, -11f); // bf-dark.hxc















                }















                else if (charName.Equals("gf-dark", StringComparison.OrdinalIgnoreCase))















                {















                    _normalBaseName = "gf";















                    _normalCharOffset = new Vector2(-45.5f, 0f); // gf-dark.hxc















                }















                else if (charName.Equals("nene-dark", StringComparison.OrdinalIgnoreCase))















                {















                    _normalBaseName = "nene"; // nene-dark.hxc















                }















                else if (charName.Equals("pico-dark", StringComparison.OrdinalIgnoreCase))















                {















                    _normalBaseName = "pico-playable"; // pico-dark.hxc uses pico-playable, not pico















                }















                else if (charName.Equals("spooky-dark", StringComparison.OrdinalIgnoreCase))















                {















                    _normalBaseName = "spooky"; // spooky-dark.hxc















                }















                else















                {















                    // Generic fallback: strip -dark suffix















                    _normalBaseName = charName.Substring(0, charName.Length - 5);















                }















            }















            















            // Parse healthBarColor from JSON (hex string like "#31B0D1")















            if (!string.IsNullOrEmpty(JsonData.HealthBarColor))















            {















                string hex = JsonData.HealthBarColor.TrimStart('#');















                if (hex.Length >= 6)















                {















                    try















                    {















                        int r = Convert.ToInt32(hex[..2], 16);















                        int g = Convert.ToInt32(hex[2..4], 16);















                        int b = Convert.ToInt32(hex[4..6], 16);















                        HealthBarColor = new Color(r, g, b);















                    }















                    catch { }















                }















            }















            















            // Build animation mappings from JSON















            if (JsonData.Animations != null && JsonData.Animations.Count > 0)















            {















                _jsonAnimMappings = new Dictionary<string, string>();















                _jsonAnimOffsets = new Dictionary<string, Vector2>();















                _jsonAnimFrameRates = new Dictionary<string, int>();















                _jsonAnimLooped = new Dictionary<string, bool>();















                _jsonAnimFrameIndices = new Dictionary<string, int[]>();















                float globalOffX = CharOffsets?.Length >= 2 ? CharOffsets[0] : 0f;















                float globalOffY = CharOffsets?.Length >= 2 ? CharOffsets[1] : 0f;















                foreach (var anim in JsonData.Animations)















                {















                    if (!string.IsNullOrEmpty(anim.Name) && !string.IsNullOrEmpty(anim.Prefix))















                    {















                        _jsonAnimMappings[anim.Name] = anim.Prefix;















                        // Original FNF: animations without explicit offsets default to globalOffsets















                        if (anim.Offsets != null && anim.Offsets.Length >= 2)















                            _jsonAnimOffsets[anim.Name] = new Vector2(anim.Offsets[0], anim.Offsets[1]);















                        else















                            // Original *Character.loadAnimations(): `if (anim.offsets == null) setAnimationOffsets(anim.name, 0, 0)`
                            // in every render type. Using globalOffsets here cancelled the global offset at draw time.
                            _jsonAnimOffsets[anim.Name] = Vector2.Zero;















                        if (anim.FrameRate > 0)















                            _jsonAnimFrameRates[anim.Name] = anim.FrameRate;















                        _jsonAnimLooped[anim.Name] = anim.Looped;















                        if (anim.FrameIndices != null && anim.FrameIndices.Length > 0)















                            _jsonAnimFrameIndices[anim.Name] = anim.FrameIndices;















                    }















                }















                // Set of all JSON prefixes. Used by fuzzy animation matching to avoid















                // grabbing a sheet key that is the EXACT prefix of a different animation















                // (e.g. "idle" must not resolve to "idle knife", which is reserved for "idle-bloody").















                _allJsonPrefixes = new HashSet<string>(_jsonAnimMappings.Values, StringComparer.OrdinalIgnoreCase);















                Console.WriteLine($"Loaded character JSON for '{charName}': {_jsonAnimMappings.Count} animations");















            }















        }















    }















    
















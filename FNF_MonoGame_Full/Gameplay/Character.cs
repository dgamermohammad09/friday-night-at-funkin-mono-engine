    /// <summary>















    /// Resolve an animation name to the actual spritesheet key without playing it.















    /// Returns null if the animation can't be found.















    /// </summary>















    protected virtual string ResolveAnimName(string anim)















    {















        if (_sprite?.Sheet == null) return null;















        















        // Check cache















        if (_animCache.TryGetValue(anim, out var cached)) return cached;















        















        // JSON mapping (strict � don't fall back to first animation)















        if (_jsonAnimMappings != null && _jsonAnimMappings.TryGetValue(anim, out var prefix))















        {















            var frames = TryMatchSheetAnimation(prefix, out string resolvedKey);















            if (frames != null && frames.Count > 0)















                return resolvedKey;















        }















        















        // Hardcoded mappings (exact then case-insensitive, matching PlayAnimation)















        if (AnimationMappings.TryGetValue(anim, out var names))















        {















            foreach (var name in names)















            {















                if (_sprite.Sheet.GetAnimation(name) != null)















                    return name;















            }















            // Case-insensitive fallback















            foreach (var name in names)















            {















                foreach (var kvp in _sprite.Sheet.Animations)















                {















                    if (kvp.Key.Equals(name, StringComparison.OrdinalIgnoreCase))















                        return kvp.Key;















                }















            }















        }















        















        // Direct name















        if (_sprite.Sheet.GetAnimation(anim) != null)















            return anim;















        















        return null;















    }















    















    /// <summary>















    /// Try to match a JSON animation prefix against actual spritesheet animation names.















    /// Uses strict matching: exact ? case-insensitive ? key.StartsWith(prefix) ?















    /// key.Contains(prefix) ? prefix.Contains(key). Does NOT fall back to the first















    /// animation, so callers can try hardcoded AnimationMappings when the JSON prefix















    /// doesn't genuinely match any spritesheet animation.















    /// </summary>















    private List<SpriteFrame> TryMatchSheetAnimation(string prefix, out string resolvedKey)















    {















        resolvedKey = prefix;















        if (_sprite?.Sheet == null) return null;















        















        // 1. Exact match















        if (_sprite.Sheet.Animations.TryGetValue(prefix, out var exact))















        {















            resolvedKey = prefix;















            return exact;















        }















        















        // 2. Case-insensitive exact match















        foreach (var kvp in _sprite.Sheet.Animations)















        {















            if (kvp.Key.Equals(prefix, StringComparison.OrdinalIgnoreCase))















            {















                resolvedKey = kvp.Key;















                return kvp.Value;















            }















        }















        















        // Fuzzy steps (3-5): a sheet key that is the EXACT prefix of a DIFFERENT animation















        // is "reserved" and must not be grabbed (e.g. "idle" must not match "idle knife",















        // which belongs to "idle-bloody"). We run two passes: first skipping reserved keys,















        // then a fallback pass allowing them so nothing regresses when no other match exists.















        bool IsReserved(string key)















            => _allJsonPrefixes != null















               && _allJsonPrefixes.Contains(key)















               && !key.Equals(prefix, StringComparison.OrdinalIgnoreCase);































        // If the requested prefix is itself a known JSON prefix, it should NEVER fall back















        // to a reserved key (e.g. clean "idle" must not play bloody "idle knife").















        bool prefixIsKnown = _allJsonPrefixes != null















                             && _allJsonPrefixes.Contains(prefix);































        for (int pass = 0; pass < 2; pass++)















        {















            // In pass 1, allow reserved keys ONLY if the prefix itself is NOT a known JSON prefix.















            // This prevents clean prefixes from accidentally matching their bloody variants.















            bool allowReserved = pass == 1 && !prefixIsKnown;































            // 3. Key starts with prefix (e.g., prefix "GF Dancing Beat" matches "GF Dancing Beat Hair blowing CAR")















            foreach (var kvp in _sprite.Sheet.Animations)















            {















                if (!allowReserved && IsReserved(kvp.Key)) continue;















                if (kvp.Key.StartsWith(prefix, StringComparison.OrdinalIgnoreCase))















                {















                    resolvedKey = kvp.Key;















                    return kvp.Value;















                }















            }































            // 4. Key contains prefix (e.g., prefix "Idle" matches "BF idle dance")















            foreach (var kvp in _sprite.Sheet.Animations)















            {















                if (!allowReserved && IsReserved(kvp.Key)) continue;















                if (kvp.Key.Contains(prefix, StringComparison.OrdinalIgnoreCase))















                {















                    resolvedKey = kvp.Key;















                    return kvp.Value;















                }















            }































            // 5. Prefix contains key (e.g., prefix "Dad idle dance" matches key "idle")















            foreach (var kvp in _sprite.Sheet.Animations)















            {















                if (!allowReserved && IsReserved(kvp.Key)) continue;















                if (prefix.Contains(kvp.Key, StringComparison.OrdinalIgnoreCase))















                {















                    resolvedKey = kvp.Key;















                    return kvp.Value;















                }















            }















        }















        















        // No genuine match found � return null so caller can try hardcoded mappings















        if (TryResolveCompositeOnly(_sprite.Sheet, prefix, out resolvedKey, out var compositeFrames))















            return compositeFrames;































        foreach (var extraSheet in _extraSheets)















        {















            if (TryResolveCompositeOnly(extraSheet, prefix, out resolvedKey, out compositeFrames))















                return compositeFrames;















        }































        return null;















    }































    private static bool TryResolveCompositeOnly(SpriteSheet sheet, string key, out string resolvedKey, out List<SpriteFrame> frames)















    {















        resolvedKey = key;















        frames = null;















        if (sheet == null) return false;































        string matchedKey = sheet.CompositeAnimations.ContainsKey(key)















            ? key















            : sheet.CompositeAnimations.Keys.FirstOrDefault(k => k.Equals(key, StringComparison.OrdinalIgnoreCase));































        if (matchedKey == null || !sheet.CompositeAnimations.TryGetValue(matchedKey, out var comp) || comp.Count == 0)















            return false;































        resolvedKey = matchedKey;















        if (!sheet.Animations.TryGetValue(matchedKey, out frames) || frames.Count == 0)















        {















            frames = new List<SpriteFrame>(comp.Count);















            for (int i = 0; i < comp.Count; i++)















                frames.Add(new SpriteFrame { Name = $"{matchedKey}_{i}" });















            sheet.Animations[matchedKey] = frames;















        }































        return true;















    }















    
















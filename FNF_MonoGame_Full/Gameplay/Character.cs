    private (int Width, int Height) GetIdleRawSize()















    {















        if (_sprite?.Sheet == null) return (0, 0);















        string[] idleNames = { "idle", "danceRight", "danceLeft" };















        foreach (var name in idleNames)















        {















            string resolved = ResolveAnimName(name);















            if (resolved == null) continue;















            // Pre-rendered composites (preRenderComposites=true): sizes stored in CompositeLogicalSizes















            if (_sprite.Sheet.CompositeLogicalSizes.TryGetValue(resolved, out var compSize) && compSize.Width > 0)















                return compSize;















            // Runtime composites (preRenderComposites=false): compute from RawCompositeData















            if (_sprite.Sheet.RawCompositeData.TryGetValue(resolved, out var rawList) && rawList.Count > 0)















                return AnimatedSprite.ComputeRawBoundingBox(rawList[0]);















        }















        // Fallback: first available pre-rendered composite















        foreach (var kvp in _sprite.Sheet.CompositeLogicalSizes)















        {















            if (kvp.Value.Width > 0)















                return kvp.Value;















        }















        // Fallback: first available runtime composite















        foreach (var kvp in _sprite.Sheet.RawCompositeData)















        {















            if (kvp.Value.Count > 0)















                return AnimatedSprite.ComputeRawBoundingBox(kvp.Value[0]);















        }















        return (0, 0);















    }















    
















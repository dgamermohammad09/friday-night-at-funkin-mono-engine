    private DateTime _dbgDrawT = DateTime.MinValue;
    public virtual void Draw(SpriteBatch spriteBatch, AssetManager assets, float cameraX = 0f, float cameraY = 0f, float zoom = 1f)















    {















        _normalChar?.Draw(spriteBatch, assets, cameraX + _normalCharOffset.X, cameraY + _normalCharOffset.Y, zoom);















        















        if (_sprite?.Sheet?.Texture != null)















        {















            // Apply per-animation offsets from character JSON















            float animOffX = 0, animOffY = 0;















            if (_jsonAnimOffsets != null && _currentAnimation != null 















                && _jsonAnimOffsets.TryGetValue(_currentAnimation, out var animOff))















            {















                animOffX = animOff.X;















                animOffY = animOff.Y;















            }















            // Apply global character offsets from JSON

            float charOffX = CharOffsets?.Length >= 2 ? CharOffsets[0] : 0f;

            float charOffY = CharOffsets?.Length >= 2 ? CharOffsets[1] : 0f;































            // Bopper.hx getScreenPosition (scroll already applied in cameraXY):















            //   output.x -= (animOffsets[0] - globalOffsets[0]) * scale.x















            //   output.y -= (animOffsets[1] - globalOffsets[1]) * scale.y















            var (drawX, drawY) = FNF_MonoGame.Engine.HaxeInterpreter.EvalGetScreenPosition(















                charX: cameraX, charY: cameraY,















                scrollX: 0f, scrollY: 0f,















                animOffsetX: animOffX, animOffsetY: animOffY,















                globalOffsetX: charOffX, globalOffsetY: charOffY,















                scaleX: Scale, scaleY: Scale);















            Vector2 drawPos = new Vector2(drawX, drawY);





































            _sprite.Position = drawPos;















            _sprite.Scale = new Vector2(Scale, Scale);















            _sprite.Effects = FlipX ? SpriteEffects.FlipHorizontally : SpriteEffects.None;















            _sprite.Tint = _trailGhostAlpha >= 0f ? new Color(Tint, _trailGhostAlpha) : Tint * Math.Clamp(_alpha, 0f, 1f);
            if (Environment.GetEnvironmentVariable("FNF_CAMLOG") == "1" && (DateTime.Now - _dbgDrawT).TotalSeconds >= 1)
            {
                _dbgDrawT = DateTime.Now;
                Console.WriteLine($"[BFDRAW] {Name} anim={_currentAnimation} drawPos={drawPos} scale={Scale} alpha={_alpha} tint={Tint} frame={_sprite.GetFrameWidth()}x{_sprite.GetFrameHeight()} sheetTex={_sprite.Sheet.Texture?.Width}x{_sprite.Sheet.Texture?.Height} tb={_sprite.Sheet.GetTimelineBounds(_sprite.ResolvedAnimName)} || {_sprite.LastDebug}");
            }















            _sprite.Draw(spriteBatch);















        }















        else















        {















            // Fallback: Draw placeholder if sprites not loaded















            DrawPlaceholder(spriteBatch, assets, cameraX, cameraY);















        }















    }















    
















    /// <summary>















    /// Apply stage JSON position to this character. Override in subclasses for render-type-specific logic.















    /// Default uses HaxeInterpreter.EvalSetScale matching BaseCharacter.hx setScale.















    /// </summary>















    public virtual void ApplyStagePosition(float[] stagePos)













    {















        if (stagePos == null || stagePos.Length < 2) return;



        _stagePos = stagePos;

        // Anchor composite (Animate atlas) drawing to the animation playing at placement (idle), like

        // the original updateHitbox() after dance(true).

        if (_sprite?.Sheet != null) _sprite.Sheet.AnchorCompositeTo(_sprite.ResolvedAnimName);


















        float w = GetFrameWidth() * Scale;















        float h = GetFrameHeight() * Scale;















        float offX = CharOffsets?.Length >= 2 ? CharOffsets[0] : 0f;















        float offY = CharOffsets?.Length >= 2 ? CharOffsets[1] : 0f;















        // Original Stage.hx addCharacter -> BaseCharacter.hx setScale:















        // this.x = stagePos - characterOrigin.x + globalOffsets[0]















        var (x, y) = FNF_MonoGame.Engine.HaxeInterpreter.EvalSetScale(















            stageX: stagePos[0], stageY: stagePos[1],















            widthAfterScale: w, heightAfterScale: h,















            globalOffsetX: offX, globalOffsetY: offY);















        // Psych Engine stage: PlayState puts the character at the stage slot (top-left) and adds the
        // character JSON "position" (startCharacterPos: char.x += positionArray[0]).
        if (StageUsesPsychPositioning && PsychCharacterOffset != null)
        {
            x = stagePos[0] + (PsychCharacterOffset.Length > 0 ? PsychCharacterOffset[0] : 0f);
            y = stagePos[1] + (PsychCharacterOffset.Length > 1 ? PsychCharacterOffset[1] : 0f);
        }
        Position = new Vector2(x, y);
        if (_sprite != null)
        {
            _sprite.PositioningFrameSize = (Width: (int)GetFrameWidth(), Height: (int)GetFrameHeight());
        }















    }
































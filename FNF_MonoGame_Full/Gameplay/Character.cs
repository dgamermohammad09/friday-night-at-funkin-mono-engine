                            cf.Tex.SaveAsPng(fs, cf.Tex.Width, cf.Tex.Height);















                            Console.WriteLine($"[TANKMAN-DEBUG] Saved idle composite to: {outPath}");















                        }















                        catch (Exception ex) { Console.WriteLine($"[TANKMAN-DEBUG] Failed to save: {ex.Message}"); }















                    }















                }















            }















        }































        // Apply scale from character JSON (default 1.0 for normal characters)















        // Original FNF: character scale comes from character JSON, NOT hardcoded.















        // Pixel characters have scale=6 in their JSON, but also set isPixel=true.















        if (JsonData != null)















        {















            Scale = JsonData.Scale;















        }















        















        _sprite.Scale = new Vector2(Scale, Scale);















        _sprite.Effects = FlipX ? SpriteEffects.FlipHorizontally : SpriteEffects.None;















        















        // Detect dual dance (GF-type characters with danceLeft/danceRight)















        _hasDualDance = ResolveAnimName("danceLeft") != null && ResolveAnimName("danceRight") != null;
        // V-Slice characters (JSON has "version"/"renderType"): Bopper dances when step % (danceEvery * 4) == 0,
        // danceEvery defaulting to 1.0 (CharacterData.DEFAULT_DANCEEVERY) for EVERY character, not only GF-type.
        // Psych characters keep Psych's rule (2 beats, GF-type 1).
        if (JsonData != null && (!string.IsNullOrEmpty(JsonData.Version) || !string.IsNullOrEmpty(JsonData.RenderType)))
            _danceInterval = Math.Max(1, (int)MathF.Round(JsonData.DanceEvery ?? 1f));
        // Original Bopper.hasDanced: onCreate dance() -> danceLeft (hasDanced=true), resetCharacter() dance() -> danceRight
        // (hasDanced=false), so the FIRST beat dance plays danceLeft. Start toggled so the next Dance() picks danceLeft.
        _danceLeft = false;















        if (_hasDualDance)















        {















            if (JsonData == null || (string.IsNullOrEmpty(JsonData.Version) && string.IsNullOrEmpty(JsonData.RenderType))) _danceInterval = 1; // Psych GF-type: every beat















            Console.WriteLine($"Character '{Name}' has dual dance (danceLeft/danceRight)");















        }















        















        // Detect -alt sing animations (parents: mom/dad alternation)















        _hasAltAnims = _jsonAnimMappings != null && _jsonAnimMappings.ContainsKey("singLEFT-alt");















        if (_hasAltAnims)















            Console.WriteLine($"Character '{Name}' has alt sing animations (mom/dad alternation)");















        















        // Play starting animation (original FNF: dance(true) then updateHitbox)















        // For dual-dance characters "idle" doesn't exist � use danceRight or startingAnimation.















        // This ensures a valid frame is loaded before GetCharacterOrigin() is called.















        string startAnim = JsonData?.StartingAnimation;















        if (_hasDualDance)















        {















            PlayAnimation(startAnim ?? "danceRight", true);















        }















        else if (startAnim != null && ResolveAnimName(startAnim) != null)















        {















            PlayAnimation(startAnim, true);















        }















        else















        {















            PlayAnimation("idle");















        }































    }















    















    public void PlayAnimation(string anim, bool force = false)















    {















        if (_sprite?.Sheet == null) return;
        if (AnimSuffix != null && anim != null && !anim.EndsWith(AnimSuffix)) anim += AnimSuffix; // sserafim-gf.hxc
        if (!string.IsNullOrEmpty(idleSuffix) && (anim == "idle" || anim == "danceLeft" || anim == "danceRight") && ResolveAnimName(anim + idleSuffix) != null) anim += idleSuffix; // Psych Alt Idle Animation































        // Tankman Bloody: after redheadsAnim, prepend -bloody variants like original tankman-bloody.hxc















        string originalAnim = anim;















        if (_isBloody && !anim.EndsWith("-bloody"))















        {















            string bloodyAnim = anim + "-bloody";















            if (_jsonAnimMappings?.ContainsKey(bloodyAnim) == true ||















                _sprite.Sheet.GetAnimation(bloodyAnim) != null ||















                _extraSheets.Any(s => s.GetAnimation(bloodyAnim) != null))















            {















                anim = bloodyAnim;















            }















        }















        if (originalAnim == "redheadsAnim")















            _isBloody = true;































        _currentAnimation = anim;















        if (Name != null && Name.Contains("tankman", StringComparison.OrdinalIgnoreCase)















            && (anim == "idle" || anim.StartsWith("sing")) && _bloodDbgLogged.Add(anim))















        {















            _animCache.TryGetValue(anim, out var cachedDbg);















            string mappedPrefix = (_jsonAnimMappings != null && _jsonAnimMappings.TryGetValue(anim, out var mp)) ? mp : "<none>";















            string resolvedDbg = ResolveAnimName(anim);















            try















            {















                if (DevFileLogs) System.IO.File.AppendAllText(@"D:\godt engine custom\FNF_MonoGame_Full\blood_debug.log",















                    $"[{DateTime.Now:HH:mm:ss}] Name='{Name}' anim='{anim}' originalAnim='{originalAnim}' _isBloody={_isBloody} prefix='{mappedPrefix}' prefixCount={_allJsonPrefixes?.Count ?? -1} cached='{cachedDbg}' resolved='{resolvedDbg}'\n");















            }















            catch { }















        }















        // Safety: if tankman is NOT bloody but resolved anim contains "knife" or "bloody", log error















        if (!_isBloody && Name?.Contains("tankman", StringComparison.OrdinalIgnoreCase) == true















            && (anim.Contains("knife") || anim.Contains("bloody")))















        {















            Console.WriteLine($"[TANKMAN-BUG] Clean tankman playing bloody anim! Name='{Name}' anim='{anim}' original='{originalAnim}'");















        }















        // Speaker GF (otis-speaker/pico-speaker) gun shots: play once then return to idle















        bool isSpeakerShoot = anim.StartsWith("shoot") && Name != null && Name.Contains("speaker") && !VSliceSingTimer; // V-Slice: shootN is a plain Bopper anim (not isSinging): pico-speaker chains shootN-hold (looped, blocks dance), otis holds the last frame until the next beat // pico-playable shoot/shootMISS are NOT sing anims: they hold the last frame until the next beat dance (Bopper)















        bool isOneShotSpeech = OneShotSpeechAnimations.Contains(originalAnim) || isSpeakerShoot;















        _isSingOrMiss = anim.StartsWith("sing") || anim.StartsWith("miss")















                     || anim == "hey" || anim == "scared" || anim == "cheer"















                     || anim == "firstDeath" || anim == "deathLoop" || anim == "deathConfirm"















                     || anim == "burpShit" || anim == "burpSmile" || anim == "burpSmileLong"















                     || anim == "shit"















                     || isOneShotSpeech;















        // Original FNF: holdTimer >= Conductor.stepCrochet * singDuration * 0.0011















        // Use actual StepCrochet for BPM-accurate hold times















        float singTime = JsonData?.SingTime ?? 4f;















        float holdTime = SingHoldSeconds(anim, singTime);















        // (V-Slice: holdTimer > singTimeSteps * stepLength; Psych chars keep stepCrochet*0.0011*singDuration)















        _isOneShotSpeechAnim = isOneShotSpeech;















        if (isOneShotSpeech)















            holdTime = 0f;















        















        // Use JSON looped flag when available, otherwise default logic















        bool shouldLoop;















        if (isOneShotSpeech)















            shouldLoop = false;















        else if (_jsonAnimLooped != null && _jsonAnimLooped.TryGetValue(anim, out bool looped))















            shouldLoop = looped;















        else















            shouldLoop = !_isSingOrMiss;















        















        // Check cache first (O(1) after first resolution)















        if (_animCache.TryGetValue(anim, out var cachedName))















        {















            _sprite.PlayAnimation(cachedName, force, shouldLoop);















            ApplyAnimFrameRate(anim);















            if (_isSingOrMiss)















                _animHoldTime = holdTime;















            _normalChar?.PlayAnimation(anim, force);
            UpdateHitbox();















            return;















        }















        















        // Try JSON animation prefix mapping first (highest priority)















        if (_jsonAnimMappings != null && _jsonAnimMappings.TryGetValue(anim, out var prefix))















        {















            // Check if this animation has specific frame indices (e.g., GF danceLeft/danceRight)















            int[] frameIndices = null;















            _jsonAnimFrameIndices?.TryGetValue(anim, out frameIndices);















            















            // Try to match the JSON prefix against actual spritesheet animation names.















            // Use strict matching (exact / case-insensitive / partial substring) � do NOT















            // fall back to the first animation, because that prevents the hardcoded















            // AnimationMappings from being tried when JSON prefixes don't match.















            var prefixFrames = TryMatchSheetAnimation(prefix, out string resolvedKey);















            if (prefixFrames != null && prefixFrames.Count > 0)















            {















                















                // If frame indices are specified, create a sub-animation with only those frames















                if (frameIndices != null && frameIndices.Length > 0)















                {















                    string subKey = $"{resolvedKey}__{anim}";















                    if (!_sprite.Sheet.Animations.ContainsKey(subKey))















                    {















                        var parentFrames = _sprite.Sheet.Animations.TryGetValue(resolvedKey, out var pf) ? pf : prefixFrames;















                        var subFrames = new List<SpriteFrame>();















                        foreach (int idx in frameIndices)















                        {















                            if (idx >= 0 && idx < parentFrames.Count)















                                subFrames.Add(parentFrames[idx]);















                        }















                        if (subFrames.Count > 0)















                            _sprite.Sheet.Animations[subKey] = subFrames;















                        















                        // Also create composite sub-animation if parent has one,















                        // so AnimatedSprite.Draw finds the pre-rendered frames for















                        // the sub-key (e.g., "GF Dancing Beat__danceLeft").















                        if (_sprite.Sheet.CompositeAnimations.TryGetValue(resolvedKey, out var parentComp))















                        {















                            var subComp = new List<(Texture2D, Rectangle, Vector2)>();















                            foreach (int idx in frameIndices)















                            {















                                if (idx >= 0 && idx < parentComp.Count)















                                    subComp.Add(parentComp[idx]);















                            }















                            if (subComp.Count > 0)















                                _sprite.Sheet.CompositeAnimations[subKey] = subComp;















                        }







                        // Sub-animations (e.g., danceRight uses frames 15-29 of "Idle") need



                        // their own logical size for correct positioning. The parent symbol's



                        // first frame size is wrong here because the sub-animation starts later.



                        if (frameIndices.Length > 0)



                        {



                            bool copiedFromParent = false;



                            // Prefer already-stored parent frame offsets/sizes (works for deferred paths



                            // where RawCompositeData has already been cleared).



                            if (_sprite.Sheet.CompositeFrameOffsets.TryGetValue(resolvedKey, out var parentOffsets) &&



                                _sprite.Sheet.CompositeFrameSizes.TryGetValue(resolvedKey, out var parentSizes) &&



                                frameIndices[0] >= 0 && frameIndices[0] < parentOffsets.Count)



                            {



                                _sprite.Sheet.CompositeLogicalSizes[subKey] = parentSizes[frameIndices[0]];



                                var subFrameOffsets = new List<Vector2>();



                                var subFrameSizes = new List<(int Width, int Height)>();



                                foreach (int idx in frameIndices)



                                {



                                    if (idx >= 0 && idx < parentOffsets.Count)



                                    {



                                        subFrameOffsets.Add(parentOffsets[idx]);



                                        subFrameSizes.Add(parentSizes[idx]);



                                    }



                                    else



                                    {



                                        subFrameOffsets.Add(Vector2.Zero);



                                        subFrameSizes.Add((0, 0));



                                    }



                                }



                                _sprite.Sheet.CompositeFrameOffsets[subKey] = subFrameOffsets;



                                _sprite.Sheet.CompositeFrameSizes[subKey] = subFrameSizes;



                                copiedFromParent = true;



                            }



                            // Fallback to raw data if still available



                            else if (_sprite.Sheet.RawCompositeData.TryGetValue(resolvedKey, out var parentRaw) &&



                                     frameIndices[0] >= 0 && frameIndices[0] < parentRaw.Count)



                            {



                                _sprite.Sheet.CompositeLogicalSizes[subKey] = AnimatedSprite.ComputeRawBoundingBox(parentRaw[frameIndices[0]]);



                                var subFrameOffsets = new List<Vector2>();



                                var subFrameSizes = new List<(int Width, int Height)>();



                                foreach (int idx in frameIndices)



                                {



                                    if (idx >= 0 && idx < parentRaw.Count)



                                    {



                                        var (minX, minY, _, _) = AnimatedSprite.ComputeRawBounds(parentRaw[idx]);



                                        subFrameOffsets.Add(new Vector2(minX, minY));



                                        subFrameSizes.Add(AnimatedSprite.ComputeRawBoundingBox(parentRaw[idx]));



                                    }



                                    else



                                    {



                                        subFrameOffsets.Add(Vector2.Zero);



                                        subFrameSizes.Add((0, 0));



                                    }



                                }



                                _sprite.Sheet.CompositeFrameOffsets[subKey] = subFrameOffsets;



                                _sprite.Sheet.CompositeFrameSizes[subKey] = subFrameSizes;



                                copiedFromParent = true;



                            }



                        }







                    }















                    if (_sprite.Sheet.Animations.ContainsKey(subKey))















                        resolvedKey = subKey;















                }















                















                _animCache[anim] = resolvedKey;















                _sprite.PlayAnimation(resolvedKey, force, shouldLoop);















                ApplyAnimFrameRate(anim);















                if (_isSingOrMiss)















                    _animHoldTime = holdTime;















                _normalChar?.PlayAnimation(anim, force);
                UpdateHitbox();















                return;















            }















        }















        















        // Resolve: try hardcoded mapped names















        if (AnimationMappings.TryGetValue(anim, out var possibleNames))















        {















            foreach (var name in possibleNames)















            {















                if (_sprite.Sheet.Animations.ContainsKey(name))















                {















                    _animCache[anim] = name;















                    _sprite.PlayAnimation(name, force, shouldLoop);















                    ApplyAnimFrameRate(anim);















                    if (_isSingOrMiss)















                        _animHoldTime = holdTime;















                    _normalChar?.PlayAnimation(anim, force);
                    UpdateHitbox();















                    return;















                }















                foreach (var kvp in _sprite.Sheet.Animations)















                {















                    if (kvp.Key.Equals(name, StringComparison.OrdinalIgnoreCase))















                    {















                        _animCache[anim] = kvp.Key;















                        _sprite.PlayAnimation(kvp.Key, force, shouldLoop);















                        ApplyAnimFrameRate(anim);















                        if (_isSingOrMiss)















                            _animHoldTime = holdTime;















                        _normalChar?.PlayAnimation(anim, force);
                        UpdateHitbox();















                        return;















                    }















                }















            }















        }















        















        // Try direct name















        var directFrames = _sprite.Sheet.GetAnimation(anim);















        if (directFrames != null && directFrames.Count > 0)















        {















            _animCache[anim] = anim;















            _sprite.PlayAnimation(anim, force, shouldLoop);















            ApplyAnimFrameRate(anim);















            if (_isSingOrMiss)















                _animHoldTime = holdTime;















            _normalChar?.PlayAnimation(anim, force);
            UpdateHitbox();















            return;















        }































        // Final fallback: resolve by anim name against composite keys















        var fallbackFrames = TryMatchSheetAnimation(anim, out var fallbackKey);















        if (fallbackFrames != null && fallbackFrames.Count > 0)















        {















            _animCache[anim] = fallbackKey;















            _sprite.PlayAnimation(fallbackKey, force, shouldLoop);















            ApplyAnimFrameRate(anim);















            if (_isSingOrMiss)















                _animHoldTime = holdTime;















            _normalChar?.PlayAnimation(anim, force);
            UpdateHitbox();















        }















    }































